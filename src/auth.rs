/// Generates a random auth entry for the client challenge.
///
/// # Examples
///
/// ```
/// use raknet_rs::generate_auth;
///
/// let (index, challenge) = generate_auth();
/// ```
///
/// # Returns
/// A tuple containing:
/// * `u8` - The index of the selected challenge in the `AUTH_TABLE` (0..255).
/// * `&'static str` - The challenge token string.
pub fn generate_auth() -> (u8, &'static str) {
    let mut rng = rand::thread_rng();
    let index = rng.gen_range(0..256) as u8;
    (index, AUTH_TABLE[index as usize].send)
}

/// Verifies that the client's response string matches the expected response hash.
///
/// # Examples
///
/// ```
/// use raknet_rs::{generate_auth, check_auth};
///
/// let (index, challenge) = generate_auth();
/// // In real scenario, receive response from client
/// // check_auth(index, response_sent_by_client);
/// ```
///
/// # Arguments
/// * `index` - The index of the challenge generated for this client.
/// * `response` - The response string sent back by the client.
///
/// # Returns
/// `true` if the response matches, `false` otherwise.
pub fn check_auth(index: u8, response: &str) -> bool {
    AUTH_TABLE[index as usize].recv == response
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_auth_table_integrity() {
        assert_eq!(AUTH_TABLE.len(), 256);
        for entry in AUTH_TABLE.iter() {
            assert!(!entry.send.is_empty());
            assert!(!entry.recv.is_empty());
        }
    }

    #[test]
    fn test_generate_and_check_auth() {
        // Run several iterations to test randomness and verification
        for _ in 0..10 {
            let (idx, challenge) = generate_auth();
            assert_eq!(challenge, AUTH_TABLE[idx as usize].send);
            
            // Expected receiver response
            let expected_response = AUTH_TABLE[idx as usize].recv;
            assert!(check_auth(idx, expected_response));

            // Incorrect response
            assert!(!check_auth(idx, "INVALID_RESPONSE_HASH"));
        }
    }
}
